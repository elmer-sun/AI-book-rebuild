def apply(fname, pairs, header, skip_if_done=False):
    path = os.path.join(BASE, fname)
    with io.open(path, "r", encoding="utf-8") as f:
        s = f.read()
    if skip_if_done and "2026-10-10 脚注已转录" in s:
        print("SKIP %s (already transcribed)" % fname)
        return
    todo = []
    for i, (old, new) in enumerate(pairs, 1):
        n = s.count(old)
        if n == 0 and s.count(new) == 1:
            continue  # already applied
        if n != 1:
            print("FAIL %s pair %d: count=%d for %r" % (fname, i, n, old[:40]))
            sys.exit(1)
        todo.append((old, new))
    for old, new in todo:
        s = s.replace(old, new)
    # 文件头注释追加（插在头注释块结束行 ===== 之前）
    marker = "% ============================================================\n\\chapter"
    idx = s.find("\\chapter")
    # 找头注释块最后一行 "% ====" 所在位置
    hdr_end = s.rfind("% ============================================================", 0, idx)
    if hdr_end < 0:
        print("FAIL header anchor in %s" % fname); sys.exit(1)
    s = s[:hdr_end] + header + s[hdr_end:]
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)
    print("OK %s: %d replacements" % (fname, len(todo)))

